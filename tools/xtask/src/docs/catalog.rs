//! The crate index, `docs/crates.md`, generated from the workspace members' manifests and the
//! dependency order of the layout rules. It is checked in; a stale one fails the stage.

use std::error::Error;
use std::fmt;
use std::path::{Path, PathBuf};

use super::Check;
use super::corpus::Corpus;
use super::fault::Fault;
use crate::error::Error as Failure;
use crate::layout::Order;

/// Why a workspace member cannot be listed.
#[derive(Debug)]
pub(crate) enum Lack {
    /// The manifest is not in the tree.
    Missing,
    /// The manifest is not TOML.
    Unread(toml::de::Error),
    /// The root manifest has no `workspace.members`.
    Memberless,
    /// The manifest has no `package.name`.
    Nameless,
    /// The manifest has no `description`, and the crate's `src/lib.rs` or `src/main.rs` no `//!` line.
    Mute,
    /// The crate has no row in the dependency order.
    Unordered,
}

impl fmt::Display for Lack {
    fn fmt(&self, out: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Missing => out.write_str("a workspace member with no Cargo.toml"),
            Self::Unread(_) => out.write_str("the manifest is not valid TOML"),
            Self::Memberless => out.write_str("no `workspace.members` list"),
            Self::Nameless => out.write_str("no `package.name`"),
            Self::Mute => {
                out.write_str("no `description` in the manifest and no `//!` line in src/lib.rs or src/main.rs")
            }
            Self::Unordered => out.write_str("no row in `MAY_USE` (tools/xtask/src/layout/rules/order.rs)"),
        }
    }
}

impl Error for Lack {
    fn source(&self) -> Option<&(dyn Error + 'static)> {
        if let Self::Unread(source) = self { Some(source) } else { None }
    }
}

/// One crate as the index lists it.
#[derive(Debug)]
struct Entry {
    name: String,
    dir: String,
    layer: String,
    purpose: String,
    uses: &'static [&'static str],
}

impl Entry {
    /// Its table row.
    fn row(&self) -> String {
        let uses = if self.uses.is_empty() {
            "none".to_owned()
        } else {
            self.uses.iter().map(|name| format!("`{name}`")).collect::<Vec<_>>().join(", ")
        };
        format!("| `{}` | `{}` | {} | {uses} |", self.name, self.dir, self.purpose.replace('|', "\\|"))
    }
}

/// The index: what it holds, and the check that the file on disk holds it.
#[derive(Debug, Clone, Copy)]
pub(crate) struct Catalog;

impl Catalog {
    /// Where the index is.
    pub(crate) const PATH: &'static str = "docs/crates.md";

    /// The head, up to the first layer.
    const HEAD: &'static str = "# Crates\n\nEvery crate of the workspace, by layer. Generated by `cargo xtask docs` from the `description` of each member's manifest and from the dependency order in `tools/xtask/src/layout/rules/order.rs`; do not edit it by hand, the docs stage fails when it is stale.\n\nA layer depends only on the layers before it, and `standalone` crates depend on nothing outside their own layer (`docs/architecture.md` section 4). The last column lists the crates of ours that a crate may depend on. Any crate may take `uses-ink-fixture` as a dev-dependency.";

    /// The table's header rows.
    const TABLE: &'static str = "| Crate | Path | Purpose | May use |\n|---|---|---|---|";

    /// The TOML at `file`.
    fn parse(corpus: &Corpus, file: &Path) -> Result<toml::Value, Lack> {
        let text = corpus.text(file).ok_or(Lack::Missing)?;
        toml::from_str(text).map_err(Lack::Unread)
    }

    /// The directories of the workspace members, as the root manifest lists them.
    fn members(corpus: &Corpus) -> Result<Vec<String>, Lack> {
        let root = Self::parse(corpus, Path::new("Cargo.toml"))?;
        let members = root
            .get("workspace")
            .and_then(|workspace| workspace.get("members"))
            .and_then(toml::Value::as_array)
            .ok_or(Lack::Memberless)?;
        Ok(members.iter().filter_map(toml::Value::as_str).map(str::to_owned).collect())
    }

    /// The manifest's description, or else the first `//!` line of the crate's entry file.
    fn purpose(corpus: &Corpus, dir: &Path, manifest: &toml::Value) -> Option<String> {
        let described =
            manifest.get("package").and_then(|package| package.get("description")).and_then(toml::Value::as_str);
        let text = described.map(str::to_owned).or_else(|| {
            ["src/lib.rs", "src/main.rs"].iter().find_map(|file| {
                let source = corpus.text(&dir.join(file))?;
                source.lines().find_map(|line| line.strip_prefix("//!")).map(str::to_owned)
            })
        })?;
        let line = text.split_whitespace().collect::<Vec<_>>().join(" ");
        (!line.is_empty()).then_some(line)
    }

    /// The crate in `dir`.
    fn entry(corpus: &Corpus, dir: &str) -> Result<Entry, Fault> {
        let file = Path::new(dir).join("Cargo.toml");
        let fail = |lack: Lack| Fault::Crate { file: file.clone(), lack };
        let manifest = Self::parse(corpus, &file).map_err(&fail)?;
        let name = manifest
            .get("package")
            .and_then(|package| package.get("name"))
            .and_then(toml::Value::as_str)
            .ok_or_else(|| fail(Lack::Nameless))?;
        let purpose = Self::purpose(corpus, Path::new(dir), &manifest).ok_or_else(|| fail(Lack::Mute))?;
        let uses = Order::allowed(name).ok_or_else(|| fail(Lack::Unordered))?;
        let layer = dir
            .strip_prefix("crates/")
            .and_then(|rest| rest.split_once('/'))
            .map_or_else(|| dir.split('/').next().unwrap_or(dir), |(layer, _)| layer);
        Ok(Entry { name: name.to_owned(), dir: dir.to_owned(), layer: layer.to_owned(), purpose, uses })
    }

    /// The index of the workspace of `corpus`, or the faults that keep it from being written.
    pub(crate) fn render(corpus: &Corpus) -> Result<String, Vec<Fault>> {
        let members =
            Self::members(corpus).map_err(|lack| vec![Fault::Crate { file: PathBuf::from("Cargo.toml"), lack }])?;
        let (found, faults): (Vec<_>, Vec<_>) =
            members.iter().map(|dir| Self::entry(corpus, dir)).partition(Result::is_ok);
        if !faults.is_empty() {
            return Err(faults.into_iter().filter_map(Result::err).collect());
        }
        let mut entries: Vec<Entry> = found.into_iter().filter_map(Result::ok).collect();
        let order = &corpus.config.layers.order;
        let rank = |layer: &str| order.iter().position(|known| known == layer).unwrap_or(order.len());
        entries
            .sort_by(|left, right| rank(&left.layer).cmp(&rank(&right.layer)).then_with(|| left.dir.cmp(&right.dir)));
        let mut layers: Vec<&str> = Vec::new();
        for entry in &entries {
            if !layers.contains(&entry.layer.as_str()) {
                layers.push(&entry.layer);
            }
        }
        let mut blocks = vec![Self::HEAD.to_owned()];
        for layer in layers {
            let rows: Vec<String> = entries.iter().filter(|entry| entry.layer == layer).map(Entry::row).collect();
            blocks.push(format!("## {layer}\n\n{}\n{}", Self::TABLE, rows.join("\n")));
        }
        Ok(format!("{}\n", blocks.join("\n\n")))
    }

    /// The path written, or none when the index was already current.
    pub(super) fn update(root: &Path) -> Result<Option<PathBuf>, Failure> {
        let corpus = Corpus::read(root)?;
        let text = Self::render(&corpus).map_err(Failure::Docs)?;
        if corpus.text(Path::new(Self::PATH)) == Some(text.as_str()) {
            return Ok(None);
        }
        let path = root.join(Self::PATH);
        std::fs::write(&path, text).map_err(|source| Failure::Write { path, source })?;
        Ok(Some(PathBuf::from(Self::PATH)))
    }
}

impl Check for Catalog {
    fn check(&self, corpus: &Corpus, faults: &mut Vec<Fault>) {
        match Self::render(corpus) {
            Ok(text) if corpus.text(Path::new(Self::PATH)) != Some(text.as_str()) => {
                faults.push(Fault::Stale { path: PathBuf::from(Self::PATH) });
            }
            Ok(_) => {}
            Err(found) => faults.extend(found),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const ROOT: &str = "[workspace]\nmembers = [\"tools/xtask\", \"crates/core/model\"]\n";

    fn corpus() -> Corpus {
        Corpus::sample(&[
            ("Cargo.toml", ROOT),
            (
                "crates/core/model/Cargo.toml",
                "[package]\nname = \"uses-ink-model\"\ndescription = \"The types | here\"\n",
            ),
            ("tools/xtask/Cargo.toml", "[package]\nname = \"xtask\"\n"),
            ("tools/xtask/src/main.rs", "//! Repo tasks.\n//! More.\n"),
        ])
    }

    #[test]
    fn crates_are_listed_by_layer_with_a_description_or_the_header() {
        let text = Catalog::render(&corpus()).unwrap();
        let rows: Vec<&str> = text.lines().filter(|line| line.starts_with("| `")).collect();
        assert_eq!(
            rows,
            [
                "| `uses-ink-model` | `crates/core/model` | The types \\| here | none |",
                "| `xtask` | `tools/xtask` | Repo tasks. | `freehand`, `uses-ink-token` |"
            ]
        );
        assert!(text.contains("## core\n\n| Crate"), "{text}");
        assert!(text.contains("## tools\n\n| Crate"), "{text}");
    }

    #[test]
    fn a_crate_with_no_purpose_or_no_row_is_a_fault() {
        let mut corpus = corpus();
        corpus.files.retain(|doc| doc.path != Path::new("tools/xtask/src/main.rs"));
        let faults = Catalog::render(&corpus).unwrap_err();
        assert!(matches!(faults.as_slice(), [Fault::Crate { lack: Lack::Mute, .. }]), "{faults:?}");
        let corpus = Corpus::sample(&[
            ("Cargo.toml", "[workspace]\nmembers = [\"a\"]\n"),
            ("a/Cargo.toml", "[package]\nname = \"unlisted\"\ndescription = \"d\"\n"),
        ]);
        let faults = Catalog::render(&corpus).unwrap_err();
        assert!(matches!(faults.as_slice(), [Fault::Crate { lack: Lack::Unordered, .. }]), "{faults:?}");
    }

    #[test]
    fn an_index_that_matches_passes_and_any_other_is_stale() {
        let mut corpus = corpus();
        let text = Catalog::render(&corpus).unwrap();
        let mut faults = Vec::new();
        Catalog.check(&corpus, &mut faults);
        assert!(matches!(faults.as_slice(), [Fault::Stale { .. }]), "a missing index is stale");
        faults.clear();
        corpus.files.push(crate::docs::corpus::Doc { path: PathBuf::from(Catalog::PATH), text });
        Catalog.check(&corpus, &mut faults);
        assert!(faults.is_empty(), "{faults:?}");
    }
}
