//! `token/token.toml` into `token/src/generated.rs` (the pen's palette and the face stacks) and
//! `token/token.css` (the same, as custom properties on `:root`).

use std::fmt;

use heck::ToUpperCamelCase;
use proc_macro2::TokenStream;
use quote::{format_ident, quote};

use crate::error::Error;
use crate::output::Output;

const SOURCE: &str = "token/token.toml";
const TARGET: &str = "token/src/generated.rs";
const SHEET: &str = "token/token.css";

/// Font families CSS names by keyword, written without quotes.
const GENERIC: &[&str] = &[
    "serif",
    "sans-serif",
    "monospace",
    "cursive",
    "fantasy",
    "system-ui",
    "ui-serif",
    "ui-sans-serif",
    "ui-monospace",
    "ui-rounded",
    "math",
    "emoji",
    "fangsong",
];

/// What is wrong with an entry of `token/token.toml`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Flaw {
    /// A top-level key other than `colour` and `face`.
    Section,
    /// A name another entry already makes into the same CSS name or Rust variant.
    Taken,
    /// A name that is not lowercase words joined by `-`.
    Name,
    /// A colour that is not `#rrggbb`.
    Colour,
    /// A face that is not a list of plain family names.
    Stack,
}

impl fmt::Display for Flaw {
    fn fmt(&self, out: &mut fmt::Formatter<'_>) -> fmt::Result {
        out.write_str(match self {
            Self::Section => "is not a section; the sections are `colour` and `face`",
            Self::Taken => {
                "is taken: a colour and a face, or two names that differ only by `-`, share a CSS name or a Rust variant"
            }
            Self::Name => "is not a name: write lowercase words joined by `-`",
            Self::Colour => "is not a colour: write `#rrggbb`",
            Self::Stack => {
                "is not a font stack: write a list of family names, without quotes, backslashes or control characters"
            }
        })
    }
}

/// One `#rrggbb` colour.
struct Colour {
    name: String,
    rgb: [u8; 3],
}

/// One font stack.
struct Face {
    name: String,
    stack: Vec<String>,
}

pub(crate) fn write(output: &mut Output) -> Result<(), Error> {
    let text = output.read(SOURCE)?;
    let table: toml::Table = toml::from_str(&text).map_err(|source| Error::Toml { path: SOURCE.into(), source })?;
    let mut colours = Vec::new();
    let mut faces = Vec::new();
    for (key, value) in table {
        match (key.as_str(), value) {
            ("colour", toml::Value::Table(entries)) => {
                for (name, value) in entries {
                    colours.push(colour(name, &value)?);
                }
            }
            ("face", toml::Value::Table(entries)) => {
                for (name, value) in entries {
                    faces.push(face(name, value)?);
                }
            }
            _ => return Err(Error::Token { name: key, flaw: Flaw::Section }),
        }
    }
    unique(&colours, &faces)?;
    output.put_rust(TARGET, SOURCE, "token", rust(&colours, &faces))?;
    output.put(SHEET, css(&colours, &faces).as_bytes())
}

/// Every name is one CSS custom property and one Rust variant, so no two may share either.
fn unique(colours: &[Colour], faces: &[Face]) -> Result<(), Error> {
    let names = colours.iter().map(|c| &c.name).chain(faces.iter().map(|f| &f.name));
    let mut seen: Vec<(String, &String)> = Vec::new();
    for name in names {
        let variant = name.to_upper_camel_case();
        if seen.iter().any(|(v, n)| *n == name || *v == variant) {
            return Err(Error::Token { name: name.clone(), flaw: Flaw::Taken });
        }
        seen.push((variant, name));
    }
    Ok(())
}

/// A name is a Rust variant and a CSS custom property: lowercase words joined by `-`.
fn named(name: String) -> Result<String, Error> {
    let word = |w: &str| !w.is_empty() && w.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit());
    let starts = name.bytes().next().is_some_and(|b| b.is_ascii_lowercase());
    if starts && name.split('-').all(word) { Ok(name) } else { Err(Error::Token { name, flaw: Flaw::Name }) }
}

fn css(colours: &[Colour], faces: &[Face]) -> String {
    let colours = colours.iter().map(|Colour { name, rgb: [r, g, b] }| format!("  --{name}: #{r:02x}{g:02x}{b:02x};"));
    let faces = faces.iter().map(|Face { name, stack }| {
        let families: Vec<String> = stack
            .iter()
            .map(|family| if GENERIC.contains(&family.as_str()) { family.clone() } else { format!("\"{family}\"") })
            .collect();
        format!("  --{name}: {};", families.join(", "))
    });
    let lines: Vec<String> = colours.chain(faces).collect();
    format!(
        "/* Generated by `cargo xtask token` from `{SOURCE}`. Edit that file, not this one. */\n\n:root {{\n{}\n}}\n",
        lines.join("\n")
    )
}

fn colour(name: String, value: &toml::Value) -> Result<Colour, Error> {
    let name = named(name)?;
    let hex = value
        .as_str()
        .and_then(|s| s.strip_prefix('#'))
        .filter(|h| h.len() == 6 && h.bytes().all(|b| b.is_ascii_hexdigit()));
    let Some(hex) = hex else { return Err(Error::Token { name, flaw: Flaw::Colour }) };
    let byte = |at: usize| hex.get(at..at + 2).and_then(|pair| u8::from_str_radix(pair, 16).ok());
    match (byte(0), byte(2), byte(4)) {
        (Some(r), Some(g), Some(b)) => Ok(Colour { name, rgb: [r, g, b] }),
        _ => Err(Error::Token { name, flaw: Flaw::Colour }),
    }
}

fn face(name: String, value: toml::Value) -> Result<Face, Error> {
    let name = named(name)?;
    let toml::Value::Array(items) = value else { return Err(Error::Token { name, flaw: Flaw::Stack }) };
    // a family is written inside double quotes, so it may not hold one, a backslash or a control
    // character (CSS reads CR and FF as newlines)
    let plain = |family: &&str| !family.is_empty() && !family.chars().any(|c| c == '"' || c == '\\' || c.is_control());
    let stack: Option<Vec<String>> = items.into_iter().map(|v| v.as_str().filter(plain).map(str::to_owned)).collect();
    match stack {
        Some(stack) if !stack.is_empty() => Ok(Face { name, stack }),
        _ => Err(Error::Token { name, flaw: Flaw::Stack }),
    }
}

fn rust(colours: &[Colour], faces: &[Face]) -> TokenStream {
    let colours = colour_enum(colours);
    let faces = face_enum(faces);
    quote! {
        use crate::{Kind, Rgb, Unknown};
        #colours
        #faces
    }
}

fn colour_enum(colours: &[Colour]) -> TokenStream {
    let names: Vec<&str> = colours.iter().map(|c| c.name.as_str()).collect();
    let variants: Vec<_> = names.iter().map(|n| format_ident!("{}", n.to_upper_camel_case())).collect();
    let docs = colours.iter().map(|c| format!(" `{}`, #{:02x}{:02x}{:02x}", c.name, c.rgb[0], c.rgb[1], c.rgb[2]));
    let rgbs = colours.iter().map(|c| {
        let [r, g, b] = c.rgb;
        quote! { Rgb(#r, #g, #b) }
    });
    quote! {
        /// A colour of the paint box.
        #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
        pub enum Colour { #( #[doc = #docs] #variants, )* }

        impl Colour {
            /// Every colour, in the order `token.toml` gives them.
            pub const ALL: &'static [Self] = &[#(Self::#variants),*];
            /// Every colour's name, in the same order.
            pub const NAMES: &'static [&'static str] = &[#(#names),*];

            /// Its name, which is also its CSS custom property without the `--`.
            pub const fn name(self) -> &'static str {
                match self { #(Self::#variants => #names,)* }
            }

            /// Its value.
            pub const fn rgb(self) -> Rgb {
                match self { #(Self::#variants => #rgbs,)* }
            }

            /// The colour named `name`.
            pub fn named(name: &str) -> Result<Self, Unknown<'_>> {
                match name {
                    #(#names => Ok(Self::#variants),)*
                    _ => Err(Unknown { kind: Kind::Colour, name, known: Self::NAMES }),
                }
            }
        }
    }
}

fn face_enum(faces: &[Face]) -> TokenStream {
    let face_names: Vec<&str> = faces.iter().map(|f| f.name.as_str()).collect();
    let face_variants: Vec<_> = face_names.iter().map(|n| format_ident!("{}", n.to_upper_camel_case())).collect();
    let face_docs = faces.iter().map(|f| format!(" `{}`: {}", f.name, f.stack.join(", ")));
    let stacks = faces.iter().map(|f| {
        let stack = &f.stack;
        quote! { &[#(#stack),*] }
    });
    quote! {
        /// A font stack.
        #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
        pub enum Face { #( #[doc = #face_docs] #face_variants, )* }

        impl Face {
            /// Every face, in the order `token.toml` gives them.
            pub const ALL: &'static [Self] = &[#(Self::#face_variants),*];
            /// Every face's name, in the same order.
            pub const NAMES: &'static [&'static str] = &[#(#face_names),*];

            /// Its name, which is also its CSS custom property without the `--`.
            pub const fn name(self) -> &'static str {
                match self { #(Self::#face_variants => #face_names,)* }
            }

            /// Its families, first choice first.
            pub const fn stack(self) -> &'static [&'static str] {
                match self { #(Self::#face_variants => #stacks,)* }
            }

            /// The face named `name`.
            pub fn named(name: &str) -> Result<Self, Unknown<'_>> {
                match name {
                    #(#face_names => Ok(Self::#face_variants),)*
                    _ => Err(Unknown { kind: Kind::Face, name, known: Self::NAMES }),
                }
            }
        }
    }
}
