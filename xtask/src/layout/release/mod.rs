//! The rule over release configuration: what dist builds, the workflow that runs it, and
//! the self-host image all name the same binary, and the image's command is one `ink` has
//! (docs/release.md).

use std::path::{Path, PathBuf};

use heck::ToKebabCase as _;

use crate::layout::model::{Crate, Workspace};
use crate::layout::{Problem, Problems, Rule};

/// The release files, read against the crates they name.
#[derive(Debug, Clone, Copy)]
pub(crate) struct Release;

/// One way the release files disagree with the workspace or with each other.
#[derive(Debug)]
pub(crate) enum Drift {
    /// A file that could not be read.
    Unreadable { path: PathBuf, source: std::io::Error },
    /// A file that is not TOML of the expected shape.
    Unparsed { path: PathBuf, source: toml::de::Error },
    /// No crate sets `dist = true`, or the one that does has no binary.
    NoBinary,
    /// More than one crate sets `dist = true`.
    ManyBinaries { krates: Vec<String> },
    /// `targets` in the dist config is empty.
    NoTargets,
    /// The workflow was generated by another version of dist than the config names.
    Version { expected: String, path: PathBuf },
    /// The workflow runs on something other than a version tag.
    Trigger { path: PathBuf, on: &'static str },
    /// The image builds another toolchain than `rust-toolchain.toml` pins.
    Toolchain { expected: String, found: Option<String> },
    /// The image builds another package than the one dist releases.
    Package { expected: String, found: Option<String> },
    /// The image's entrypoint is not the released binary.
    Entrypoint { expected: String, found: Option<String> },
    /// The image's command is not a command of the binary.
    Command { found: Option<String>, known: Vec<String> },
    /// The image builds the binary before it builds the components the binary embeds, or never
    /// builds them (decision 0054).
    ImageComponents,
    /// The release workflow never runs `xtask component`, so a release binary would not
    /// build (its build script refuses a release build with no components).
    WorkflowComponents { path: PathBuf },
    /// A command the image runs before it exists is listed as pending, and now it exists.
    Pending { command: &'static str },
    /// The image runs `ink serve` without an address on every interface, which a published port
    /// cannot reach (`serve` listens on the loopback by default).
    Listen { command: Vec<String> },
    /// A workflow step uses an action by a tag or branch, which its owner can move.
    Unpinned { path: PathBuf, uses: String },
    /// A workflow has no top-level `permissions:`, so every job gets the repository's default.
    NoPermissions { path: PathBuf },
    /// A workflow grants write at the top level, to every job; a job that needs it asks for it.
    WidePermissions { path: PathBuf },
    /// A tag pattern with `*`, which lets a tag name hold shell syntax into the release jobs.
    Glob { path: PathBuf, pattern: String },
    /// A `gh release` command with a `${{ }}` expression in the script text.
    Interpolated { path: PathBuf, line: String },
    /// A tool the install action fetches without a version.
    Floating { path: PathBuf, tool: String },
    /// The release workflow does not check that the tagged commit is on `main`.
    Ancestry { path: PathBuf },
    /// The Docker context is not an allowlist.
    OpenContext,
    /// The Docker context leaves out a folder or file the build reads.
    Excluded { place: String },
}

impl std::fmt::Display for Drift {
    fn fmt(&self, out: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Unreadable { path, source } => write!(out, "`{}` cannot be read: {source}", path.display()),
            Self::Unparsed { path, source } => {
                write!(out, "`{}` is not the TOML release checks read: {source}", path.display())
            }
            Self::NoBinary => write!(out, "no crate sets `dist = true` in [package.metadata.dist] and has a [[bin]]"),
            Self::ManyBinaries { krates } => {
                write!(out, "one crate releases the binary, but {} set `dist = true`", krates.join(", "))
            }
            Self::NoTargets => write!(out, "`{}` lists no targets", Release::CONFIG),
            Self::Version { expected, path } => write!(
                out,
                "`{}` was not generated by dist {expected}, which `{}` names: run `dist generate`",
                path.display(),
                Release::CONFIG
            ),
            Self::Trigger { path, on } => write!(
                out,
                "`{}` runs on `{on}`; releases run on version tags only (`pr-run-mode = \"skip\"`)",
                path.display()
            ),
            _ => self.rest(out),
        }
    }
}

impl Drift {
    /// The problems with the workflows and the Docker context.
    fn rest(&self, out: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Unpinned { path, uses } => {
                write!(out, "`{}` uses `{uses}`: pin it to a full commit hash, the tag in a comment", path.display())
            }
            Self::NoPermissions { path } => {
                write!(
                    out,
                    "`{}` has no top-level `permissions:`; set `contents: read` and widen per job",
                    path.display()
                )
            }
            Self::WidePermissions { path } => {
                write!(out, "`{}` grants write to every job; grant it to the one job that needs it", path.display())
            }
            Self::Glob { path, pattern } => {
                write!(
                    out,
                    "`{}` triggers on `{pattern}`; a tag pattern holds no `*`, so the name is shell-safe",
                    path.display()
                )
            }
            Self::Interpolated { path, line } => {
                write!(out, "`{}` puts an expression in a script: `{line}`; pass it through `env:`", path.display())
            }
            Self::Floating { path, tool } => {
                write!(out, "`{}` installs `{tool}` with no version; write `{tool}@X.Y.Z`", path.display())
            }
            Self::Ancestry { path } => write!(
                out,
                "`{}` never runs `git merge-base --is-ancestor` on the tagged commit and `origin/main`",
                path.display()
            ),
            Self::OpenContext => {
                write!(out, "`.dockerignore` must start with `*`, then allow what the build reads with `!`")
            }
            Self::Excluded { place } => {
                write!(out, "`.dockerignore` leaves out `{place}`, which the image build reads")
            }
            _ => self.image(out),
        }
    }

    /// The problems with the Dockerfile.
    fn image(&self, out: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let shown = |found: &Option<String>| found.as_deref().map_or("nothing".to_owned(), |f| format!("`{f}`"));
        match self {
            Self::Toolchain { expected, found } => {
                write!(out, "the Dockerfile builds rust {}, rust-toolchain.toml pins `{expected}`", shown(found))
            }
            Self::Package { expected, found } => {
                write!(out, "the Dockerfile builds {}, dist releases `{expected}`", shown(found))
            }
            Self::Entrypoint { expected, found } => {
                write!(out, "the Dockerfile's ENTRYPOINT is {}, the binary is `{expected}`", shown(found))
            }
            Self::Command { found, known } => write!(
                out,
                "the Dockerfile's CMD is {}, not a command of the binary ({}, or one of Release::PENDING)",
                shown(found),
                known.join(", ")
            ),
            Self::ImageComponents => write!(
                out,
                "the Dockerfile must run `xtask component` in a RUN before the `cargo build` that embeds them"
            ),
            Self::WorkflowComponents { path } => {
                write!(out, "`{}` never runs `xtask component` before dist builds the binary", path.display())
            }
            Self::Pending { command } => {
                write!(out, "`{command}` exists now: remove it from Release::PENDING in xtask's release rule")
            }
            Self::Listen { command } => write!(
                out,
                "the Dockerfile's CMD is `{}`; `serve` needs `--addr 0.0.0.0:<port>` to be reachable from the host",
                command.join(" ")
            ),
            _ => Ok(()),
        }
    }
}

impl Release {
    /// The dist config.
    pub(crate) const CONFIG: &'static str = "dist-workspace.toml";
    const WORKFLOW: &'static str = ".github/workflows/release.yml";
    const WORKFLOWS: &'static str = ".github/workflows";
    const IGNORE: &'static str = ".dockerignore";
    /// Files outside every crate that the image build reads.
    const ROOT: &'static [&'static str] = &["Cargo.toml", "Cargo.lock", "rust-toolchain.toml"];
    const DOCKERFILE: &'static str = "Dockerfile";
    const TOOLCHAIN: &'static str = "rust-toolchain.toml";

    /// Commands the image runs that the binary does not have yet. None now: `serve` was the last
    /// (M3). The rule fails once a command exists and is still listed, so this list only shrinks.
    const PENDING: &'static [&'static str] = &[];

    fn text(root: &Path, name: &str) -> Result<String, Drift> {
        let path = root.join(name);
        std::fs::read_to_string(&path).map_err(|source| Drift::Unreadable { path: name.into(), source })
    }

    fn table(root: &Path, name: &str) -> Result<toml::Table, Drift> {
        let text = Self::text(root, name)?;
        toml::from_str(&text).map_err(|source| Drift::Unparsed { path: name.into(), source })
    }

    /// The crate dist releases and the binary it builds.
    fn binary(workspace: &Workspace) -> Result<(&Crate, String), Drift> {
        let mut marked = Vec::new();
        for krate in &workspace.crates {
            let manifest = Self::table(&workspace.root, &format!("{}/Cargo.toml", krate.place()))?;
            let dist = manifest.get("package").and_then(|p| p.get("metadata")).and_then(|m| m.get("dist"));
            if dist.and_then(|d| d.get("dist")).and_then(toml::Value::as_bool) == Some(true) {
                let bin = manifest.get("bin").and_then(toml::Value::as_array).and_then(|b| b.first());
                let name = bin.and_then(|b| b.get("name")).and_then(toml::Value::as_str);
                marked.push((krate, name.map(str::to_owned)));
            }
        }
        match marked.as_slice() {
            [(krate, Some(name))] => Ok((krate, name.clone())),
            [] | [(_, None)] => Err(Drift::NoBinary),
            many => Err(Drift::ManyBinaries { krates: many.iter().map(|(k, _)| k.name.clone()).collect() }),
        }
    }

    /// The commands of the binary, as a user types them: the variants of its `Command` enum.
    fn commands(krate: &Crate) -> Vec<String> {
        let items = krate.modules.iter().flat_map(|m| &m.syntax.items);
        items
            .filter_map(|item| match item {
                syn::Item::Enum(found) if found.ident == "Command" => Some(found),
                _ => None,
            })
            .flat_map(|found| found.variants.iter().map(|v| v.ident.to_string().to_kebab_case()))
            .collect()
    }

    fn config(root: &Path) -> Result<(String, usize), Drift> {
        let config = Self::table(root, Self::CONFIG)?;
        let dist = config.get("dist").and_then(toml::Value::as_table);
        let version = dist.and_then(|d| d.get("cargo-dist-version")).and_then(toml::Value::as_str);
        let targets = dist.and_then(|d| d.get("targets")).and_then(toml::Value::as_array);
        Ok((version.unwrap_or_default().to_owned(), targets.map_or(0, Vec::len)))
    }

    /// The Dockerfile against the toolchain, the released crate and binary, and the commands.
    fn image(root: &Path, krate: &Crate, binary: &str) -> Result<Vec<Drift>, Drift> {
        let mut found = Vec::new();
        let dockerfile = Dockerfile::new(&Self::text(root, Self::DOCKERFILE)?);
        let channel = Self::table(root, Self::TOOLCHAIN)?
            .get("toolchain")
            .and_then(|t| t.get("channel"))
            .and_then(toml::Value::as_str)
            .unwrap_or_default()
            .to_owned();
        let image = dockerfile.keyword("FROM").find_map(|rest| rest.strip_prefix("rust:"));
        let tag = image.map(|rest| rest.split(['-', '@', ' ']).next().unwrap_or(rest).to_owned());
        if tag.as_deref() != Some(channel.as_str()) {
            found.push(Drift::Toolchain { expected: channel, found: tag });
        }
        let runs = dockerfile.keyword("RUN").collect::<Vec<_>>().join("\n");
        let (built, embedded) = (runs.find("xtask component"), runs.find("cargo build"));
        if built.is_none() || embedded.is_none() || built > embedded {
            found.push(Drift::ImageComponents);
        }
        let package = dockerfile.after("--package");
        if package.as_deref() != Some(krate.name.as_str()) {
            found.push(Drift::Package { expected: krate.name.clone(), found: package });
        }
        let entry = dockerfile.exec("ENTRYPOINT").into_iter().next();
        if entry.as_deref() != Some(binary) {
            found.push(Drift::Entrypoint { expected: binary.to_owned(), found: entry });
        }
        found.extend(Self::command(&dockerfile, krate));
        Ok(found)
    }

    /// The Dockerfile's `CMD` against the commands the binary knows and the ones still pending.
    fn command(dockerfile: &Dockerfile, krate: &Crate) -> Vec<Drift> {
        let mut found = Vec::new();
        let words = dockerfile.exec("CMD");
        let command = words.first().cloned();
        let known = Self::commands(krate);
        let on_all = words
            .windows(2)
            .any(|pair| matches!(pair, [flag, addr] if flag == "--addr" && addr.starts_with("0.0.0.0:")));
        if command.as_deref() == Some("serve") && !on_all {
            found.push(Drift::Listen { command: words.clone() });
        }
        match command.as_deref() {
            Some(name) if known.iter().any(|k| k == name) => {
                if let Some(pending) = Self::PENDING.iter().find(|p| **p == name) {
                    found.push(Drift::Pending { command: pending });
                }
            }
            Some(name) if Self::PENDING.contains(&name) => {}
            _ => found.push(Drift::Command { found: command, known }),
        }
        found
    }

    fn drift(workspace: &Workspace) -> Result<Vec<Drift>, Drift> {
        let root = workspace.root.as_path();
        let mut found = Vec::new();
        let (krate, binary) = Self::binary(workspace)?;
        let (version, targets) = Self::config(root)?;
        if targets == 0 {
            found.push(Drift::NoTargets);
        }

        let workflow = Self::text(root, Self::WORKFLOW)?;
        if !workflow.contains(&format!("cargo-dist/releases/download/v{version}/")) {
            found.push(Drift::Version { expected: version, path: Self::WORKFLOW.into() });
        }
        if !workflow.contains("xtask component") {
            found.push(Drift::WorkflowComponents { path: Self::WORKFLOW.into() });
        }
        for on in ["pull_request:", "pull_request_target:", "workflow_dispatch:", "schedule:", "branches:"] {
            if workflow.lines().any(|line| line.trim_start().starts_with(on)) {
                found.push(Drift::Trigger { path: Self::WORKFLOW.into(), on: on.trim_end_matches(':') });
            }
        }

        if !workflow.contains("merge-base --is-ancestor") {
            found.push(Drift::Ancestry { path: Self::WORKFLOW.into() });
        }
        for flow in Workflow::all(root)? {
            found.extend(flow.drift());
        }

        found.extend(Self::context(root, workspace)?);
        found.extend(Self::image(root, krate, &binary)?);
        Ok(found)
    }

    /// The Docker context against the folders and files the build reads.
    fn context(root: &Path, workspace: &Workspace) -> Result<Vec<Drift>, Drift> {
        let text = Self::text(root, Self::IGNORE)?;
        let rules = text.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')).collect::<Vec<_>>();
        let mut found = Vec::new();
        if rules.first() != Some(&"*") {
            found.push(Drift::OpenContext);
        }
        let allowed = rules.iter().filter_map(|rule| rule.strip_prefix('!')).map(|a| a.trim_end_matches('/'));
        let allowed = allowed.collect::<Vec<_>>();
        let places = workspace.crates.iter().map(Crate::place).chain(Self::ROOT.iter().map(|r| (*r).to_owned()));
        for place in places {
            if !allowed.iter().any(|a| place == *a || place.starts_with(&format!("{a}/"))) {
                found.push(Drift::Excluded { place });
            }
        }
        Ok(found)
    }
}

/// A workflow file, read for the rules every one of them keeps.
#[derive(Debug)]
struct Workflow {
    path: PathBuf,
    text: String,
}

impl Workflow {
    /// Every workflow under `.github/workflows`, in name order.
    fn all(root: &Path) -> Result<Vec<Self>, Drift> {
        let dir = root.join(Release::WORKFLOWS);
        let unread = |source| Drift::Unreadable { path: Release::WORKFLOWS.into(), source };
        let mut names = std::fs::read_dir(&dir)
            .map_err(unread)?
            .map(|entry| entry.map(|e| e.file_name()))
            .collect::<Result<Vec<_>, _>>()
            .map_err(unread)?;
        names.sort();
        let mut flows = Vec::new();
        for name in names.into_iter().filter(|n| n.to_string_lossy().ends_with(".yml")) {
            let path = PathBuf::from(Release::WORKFLOWS).join(name);
            let text = std::fs::read_to_string(root.join(&path))
                .map_err(|source| Drift::Unreadable { path: path.clone(), source })?;
            flows.push(Self { path, text });
        }
        Ok(flows)
    }

    fn drift(&self) -> Vec<Drift> {
        let mut found = self.pins();
        found.extend(self.permits());
        found.extend(self.globs());
        found.extend(self.shells());
        found.extend(self.tools());
        found
    }

    /// The value of every `key:` line, comment cut off, quotes and list dashes removed.
    fn values<'a>(&'a self, key: &'a str) -> impl Iterator<Item = &'a str> {
        self.text.lines().filter_map(move |line| {
            let rest = line.trim().trim_start_matches("- ").strip_prefix(key)?;
            Some(rest.split(" #").next().unwrap_or(rest).trim().trim_matches(['"', '\'']))
        })
    }

    /// Every `uses:` that is not a local path or a full commit hash.
    fn pins(&self) -> Vec<Drift> {
        let hashed = |rev: &str| rev.len() == 40 && rev.chars().all(|c| c.is_ascii_hexdigit());
        let unpinned = self.values("uses:").filter(|uses| !uses.starts_with("./"));
        unpinned
            .filter(|uses| !uses.split_once('@').is_some_and(|(_, rev)| hashed(rev)))
            .map(|uses| Drift::Unpinned { path: self.path.clone(), uses: uses.to_owned() })
            .collect()
    }

    /// The top-level `permissions:` block: present, and with no write in it.
    fn permits(&self) -> Option<Drift> {
        let mut lines = self.text.lines().skip_while(|line| !line.starts_with("permissions:"));
        let Some(head) = lines.next() else { return Some(Drift::NoPermissions { path: self.path.clone() }) };
        let body = lines.take_while(|line| line.is_empty() || line.starts_with(char::is_whitespace));
        let wide = std::iter::once(head).chain(body).any(|line| line.contains("write"));
        wide.then(|| Drift::WidePermissions { path: self.path.clone() })
    }

    /// Tag patterns under `tags:` that hold a `*`.
    fn globs(&self) -> Vec<Drift> {
        let after = self.text.lines().map(str::trim).skip_while(|line| *line != "tags:").skip(1);
        let patterns = after.take_while(|line| line.starts_with("- "));
        patterns
            .filter(|pattern| pattern.contains('*'))
            .map(|pattern| Drift::Glob { path: self.path.clone(), pattern: pattern.to_owned() })
            .collect()
    }

    /// `gh release` lines that carry a `${{ }}` expression.
    fn shells(&self) -> Vec<Drift> {
        let lines = self.text.lines().map(str::trim);
        lines
            .filter(|line| line.contains("gh release") && line.contains("${{"))
            .map(|line| Drift::Interpolated { path: self.path.clone(), line: line.to_owned() })
            .collect()
    }

    /// Tools of the install action that name no version.
    fn tools(&self) -> Vec<Drift> {
        let entries = self.values("tool:").flat_map(|list| list.split(','));
        entries
            .map(str::trim)
            .filter(|tool| !tool.contains('@'))
            .map(|tool| Drift::Floating { path: self.path.clone(), tool: tool.to_owned() })
            .collect()
    }
}

impl Rule for Release {
    const NAME: &'static str = "release";

    fn check(&self, workspace: &Workspace, problems: &mut Problems) {
        match Self::drift(workspace) {
            Ok(found) => found.into_iter().for_each(|drift| problems.push(Problem::Release(drift))),
            Err(drift) => problems.push(Problem::Release(drift)),
        }
    }
}

/// A Dockerfile as instructions: the keyword and the rest of each line.
#[derive(Debug)]
struct Dockerfile {
    lines: Vec<(String, String)>,
}

impl Dockerfile {
    /// Reads `text`, joining `\` continuations and skipping comments.
    fn new(text: &str) -> Self {
        let joined = text.replace("\\\n", " ");
        let lines = joined
            .lines()
            .map(str::trim)
            .filter(|line| !line.is_empty() && !line.starts_with('#'))
            .map(|line| match line.split_once(char::is_whitespace) {
                Some((keyword, rest)) => (keyword.to_uppercase(), rest.trim().to_owned()),
                None => (line.to_uppercase(), String::new()),
            })
            .collect();
        Self { lines }
    }

    /// The rest of every line that starts with `keyword`.
    fn keyword<'a>(&'a self, keyword: &'a str) -> impl Iterator<Item = &'a str> {
        self.lines.iter().filter(move |(k, _)| k == keyword).map(|(_, rest)| rest.as_str())
    }

    /// The word after `flag` in any line.
    fn after(&self, flag: &str) -> Option<String> {
        let words = self.lines.iter().flat_map(|(_, rest)| rest.split_whitespace());
        words.clone().zip(words.skip(1)).find(|(word, _)| *word == flag).map(|(_, next)| next.to_owned())
    }

    /// The last `keyword` line read as an exec-form array, `["a", "b"]`.
    fn exec(&self, keyword: &str) -> Vec<String> {
        let Some(rest) = self.keyword(keyword).last() else { return Vec::new() };
        let inner = rest.trim().trim_start_matches('[').trim_end_matches(']');
        inner.split(',').map(|word| word.trim().trim_matches('"').to_owned()).filter(|w| !w.is_empty()).collect()
    }
}

#[cfg(test)]
mod tests {
    use super::{Drift, Workflow};

    fn flow(text: &str) -> Workflow {
        Workflow { path: "w.yml".into(), text: text.to_owned() }
    }

    const HASH: &str = "3d3c42e5aac5ba805825da76410c181273ba90b1";

    #[test]
    fn a_moving_tag_is_unpinned() {
        let text = format!("- uses: actions/checkout@v7\n- uses: a/b@{HASH} # v1\n- uses: ./local\n");
        let found = flow(&text).pins();
        assert!(
            matches!(found.as_slice(), [Drift::Unpinned { uses, .. }] if uses == "actions/checkout@v7"),
            "{found:?}"
        );
    }

    #[test]
    fn write_at_the_top_is_wide() {
        assert!(matches!(flow("permissions:\n  contents: write\n").permits(), Some(Drift::WidePermissions { .. })));
        assert!(matches!(flow("name: x\njobs: {}\n").permits(), Some(Drift::NoPermissions { .. })));
        let jobs =
            "permissions:\n  \"contents\": \"read\"\n\njobs:\n  host:\n    permissions:\n      contents: write\n";
        assert!(flow(jobs).permits().is_none());
    }

    #[test]
    fn a_star_in_a_tag_pattern_is_found() {
        let found = flow("on:\n  push:\n    tags:\n      - 'v[0-9]+'\n      - '**[0-9]*'\n").globs();
        assert!(matches!(found.as_slice(), [Drift::Glob { pattern, .. }] if pattern.contains("**")), "{found:?}");
    }

    #[test]
    fn an_expression_in_a_release_command_is_found() {
        let text = "gh release create \"${{ needs.plan.outputs.tag }}\"\ngh release create \"$TAG\"\n";
        assert_eq!(flow(text).shells().len(), 1);
    }

    #[test]
    fn a_tool_with_no_version_is_floating() {
        let found = flow("  tool: cargo-nextest@0.9.1,wasmtime\n").tools();
        assert!(matches!(found.as_slice(), [Drift::Floating { tool, .. }] if tool == "wasmtime"), "{found:?}");
    }
}
