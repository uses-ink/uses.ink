//! What the release rule finds: [`Drift`], one way the release files disagree.

use std::path::PathBuf;

use super::Release;

/// One way the release files disagree with the workspace or with each other.
#[derive(Debug)]
pub(crate) enum Drift {
    /// A file that could not be read.
    Unreadable { path: PathBuf, source: std::io::Error },
    /// A file that is not TOML of the expected shape.
    Unparsed { path: PathBuf, source: toml::de::Error },
    /// No crate sets `dist = true`, or the one that does has no binary.
    NoBinary,
    /// More than one crate sets `dist = true`.
    ManyBinaries { krates: Vec<String> },
    /// `targets` in the dist config is empty.
    NoTargets,
    /// The workflow was generated by another version of dist than the config names.
    Version { expected: String, path: PathBuf },
    /// The workflow runs on something other than a version tag.
    Trigger { path: PathBuf, on: &'static str },
    /// The image builds another toolchain than `rust-toolchain.toml` pins.
    Toolchain { expected: String, found: Option<String> },
    /// The image builds another package than the one dist releases.
    Package { expected: String, found: Option<String> },
    /// The image's entrypoint is not the released binary.
    Entrypoint { expected: String, found: Option<String> },
    /// The image's command is not a command of the binary.
    Command { found: Option<String>, known: Vec<String> },
    /// The image builds the binary before it builds the components the binary embeds, or never
    /// builds them (decision 0054).
    ImageComponents,
    /// The release workflow never runs `xtask component`, so a release binary would not
    /// build (its build script refuses a release build with no components).
    WorkflowComponents { path: PathBuf },
    /// A command the image runs before it exists is listed as pending, and now it exists.
    Pending { command: &'static str },
    /// The image runs `ink serve` without an address on every interface, which a published port
    /// cannot reach (`serve` listens on the loopback by default).
    Listen { command: Vec<String> },
    /// A workflow step uses an action by a tag or branch, which its owner can move.
    Unpinned { path: PathBuf, uses: String },
    /// A workflow has no top-level `permissions:`, so every job gets the repository's default.
    NoPermissions { path: PathBuf },
    /// A workflow grants write at the top level, to every job; a job that needs it asks for it.
    WidePermissions { path: PathBuf },
    /// A tag pattern with `*`, which lets a tag name hold shell syntax into the release jobs.
    Glob { path: PathBuf, pattern: String },
    /// A `gh release` command with a `${{ }}` expression in the script text.
    Interpolated { path: PathBuf, line: String },
    /// A tool the install action fetches without a version.
    Floating { path: PathBuf, tool: String },
    /// The release workflow does not check that the tagged commit is on `main`.
    Ancestry { path: PathBuf },
    /// The Docker context is not an allowlist.
    OpenContext,
    /// The Docker context leaves out a folder or file the build reads.
    Excluded { place: String },
}

impl std::fmt::Display for Drift {
    fn fmt(&self, out: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Unreadable { path, source } => write!(out, "`{}` cannot be read: {source}", path.display()),
            Self::Unparsed { path, source } => {
                write!(out, "`{}` is not the TOML release checks read: {source}", path.display())
            }
            Self::NoBinary => write!(out, "no crate sets `dist = true` in [package.metadata.dist] and has a [[bin]]"),
            Self::ManyBinaries { krates } => {
                write!(out, "one crate releases the binary, but {} set `dist = true`", krates.join(", "))
            }
            Self::NoTargets => write!(out, "`{}` lists no targets", Release::CONFIG),
            Self::Version { expected, path } => write!(
                out,
                "`{}` was not generated by dist {expected}, which `{}` names: run `dist generate`",
                path.display(),
                Release::CONFIG
            ),
            Self::Trigger { path, on } => write!(
                out,
                "`{}` runs on `{on}`; releases run on version tags only (`pr-run-mode = \"skip\"`)",
                path.display()
            ),
            _ => self.rest(out),
        }
    }
}

impl Drift {
    /// The problems with the workflows and the Docker context.
    fn rest(&self, out: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Unpinned { path, uses } => {
                write!(out, "`{}` uses `{uses}`: pin it to a full commit hash, the tag in a comment", path.display())
            }
            Self::NoPermissions { path } => {
                write!(
                    out,
                    "`{}` has no top-level `permissions:`; set `contents: read` and widen per job",
                    path.display()
                )
            }
            Self::WidePermissions { path } => {
                write!(out, "`{}` grants write to every job; grant it to the one job that needs it", path.display())
            }
            Self::Glob { path, pattern } => {
                write!(
                    out,
                    "`{}` triggers on `{pattern}`; a tag pattern holds no `*`, so the name is shell-safe",
                    path.display()
                )
            }
            Self::Interpolated { path, line } => {
                write!(out, "`{}` puts an expression in a script: `{line}`; pass it through `env:`", path.display())
            }
            Self::Floating { path, tool } => {
                write!(out, "`{}` installs `{tool}` with no version; write `{tool}@X.Y.Z`", path.display())
            }
            Self::Ancestry { path } => write!(
                out,
                "`{}` never runs `git merge-base --is-ancestor` on the tagged commit and `origin/main`",
                path.display()
            ),
            Self::OpenContext => {
                write!(out, "`.dockerignore` must start with `*`, then allow what the build reads with `!`")
            }
            Self::Excluded { place } => {
                write!(out, "`.dockerignore` leaves out `{place}`, which the image build reads")
            }
            _ => self.image(out),
        }
    }

    /// The problems with the Dockerfile.
    fn image(&self, out: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let shown = |found: &Option<String>| found.as_deref().map_or("nothing".to_owned(), |f| format!("`{f}`"));
        match self {
            Self::Toolchain { expected, found } => {
                write!(out, "the Dockerfile builds rust {}, rust-toolchain.toml pins `{expected}`", shown(found))
            }
            Self::Package { expected, found } => {
                write!(out, "the Dockerfile builds {}, dist releases `{expected}`", shown(found))
            }
            Self::Entrypoint { expected, found } => {
                write!(out, "the Dockerfile's ENTRYPOINT is {}, the binary is `{expected}`", shown(found))
            }
            Self::Command { found, known } => write!(
                out,
                "the Dockerfile's CMD is {}, not a command of the binary ({}, or one of Release::PENDING)",
                shown(found),
                known.join(", ")
            ),
            Self::ImageComponents => write!(
                out,
                "the Dockerfile must run `xtask component` in a RUN before the `cargo build` that embeds them"
            ),
            Self::WorkflowComponents { path } => {
                write!(out, "`{}` never runs `xtask component` before dist builds the binary", path.display())
            }
            Self::Pending { command } => {
                write!(out, "`{command}` exists now: remove it from Release::PENDING in xtask's release rule")
            }
            Self::Listen { command } => write!(
                out,
                "the Dockerfile's CMD is `{}`; `serve` needs `--addr 0.0.0.0:<port>` to be reachable from the host",
                command.join(" ")
            ),
            _ => Ok(()),
        }
    }
}
